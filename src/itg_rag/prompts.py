def context_prompt(
    question: str, hits: list[SearchHit], schema: type[Schema] = AnswerDraft
) -> str:
    return json.dumps(
        {
            "question": question,
            "context": [
                {
                    "chunk_id": hit.chunk.chunk_id,
                    "source_name": hit.chunk.source_name,
                    "text": hit.chunk.text,
                }
                for hit in hits
            ],
            "response_schema": schema.model_json_schema(),
        },
        ensure_ascii=False,
    )
